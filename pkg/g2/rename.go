// RenamePackage puts the package's definition under the name its repository has now, in a
// pull request into the default branch.
//
// The package's directory doesn't move, which is what naming it after an id is for: a
// rename used to carry the whole package over, and everything that had written the old name
// down was left pointing at nothing. What has to change is the definition, because the
// definition is the only thing that says which package the directory holds -- one still
// naming the old package would be found under a name nobody uses, and a run asking for the
// new name would find nothing and take the package over a second time.
//
// The old name becomes an alias, which is how a configuration still asking for it resolves.
//
// It returns the definition as the pull request writes it, and nil when there was nothing to
// do: a definition that already names the new package is what a second run of the same
// rename sees.
func (c *Client) RenamePackage(ctx context.Context, logger *slog.Logger, from, to string) (*aquag2.Config, error) {
	if _, ok := c.Dir(from); !ok {
		return nil, fmt.Errorf("%w: %s", errNoBranchToRename, from)
	}
	head, _ := c.HeadBranch(from)
	parent, err := c.BranchSHA(ctx, DefaultBranch)
	if err != nil {
		return nil, err
	}

	cfg, err := c.Config(ctx, from)
	if err != nil {
		return nil, err
	}
	if cfg == nil {
		return nil, fmt.Errorf("%w: %s", errNoConfigToRename, from)
	}
	if cfg.Name == to {
		return nil, nil //nolint:nilnil // nothing to do, which is not a definition
	}
	dir, _ := c.Dir(from)
	raw, err := c.File(ctx, DefaultBranch, dir+"/"+ConfigFileName)
	if err != nil {
		return nil, err
	}
	content, err := renamedConfig(cfg, raw, from, to)
	if err != nil {
		return nil, err
	}

	title := fmt.Sprintf("fix(%s): rename the package to %s", from, to)
	if err := c.CommitPackage(ctx, logger, from, head, parent, title, []*File{{
		Path:    ConfigFileName,
		Content: content,
	}}); err != nil {
		return nil, fmt.Errorf("commit the renamed definition: %w", err)
	}
	pr, err := c.CreatePullRequestFrom(ctx, logger, head, DefaultBranch, title, renameBody(from, to))
	if err != nil {
		return nil, fmt.Errorf("open the pull request that renames the package: %w", err)
	}
	logger.Info("opened the pull request that renames the package",
		"from", from, "to", to, "number", pr.GetNumber())
	return cfg, nil
}

// renameBody says what the pull request does and what waits on it.
func renameBody(from, to string) string {
	return fmt.Sprintf(`Generated by ar2.

%s answers to %s now. The definition is what says which package its directory holds, so
it is what the rename changes; the directory itself is named after the package's id and
doesn't move.

The old name is kept as an alias, which is how a configuration still asking for %s resolves.

Until this merges, the registry still holds the package under %s: a run asking for the new
name finds nothing under it.
`, from, to, from, from)
}

// renamedConfig is the definition under the new name, as the file raw is with what the rename
// changes and nothing else.
//
// The old name becomes an alias, kept alongside the ones it already had rather than
// replacing them: a package renamed twice has to answer to both of its old names, and a
// definition recording only the last one would leave the older pointing at a name
// nothing holds any more.
//
// The file is edited rather than rendered again from cfg. A definition is a file a maintainer
// edits: rendering it again moved repo_id to the end, indented every list another way and
// would have dropped any comment in it, all in a pull request about a name. cfg is changed the
// same way, for what reads it after.
func renamedConfig(cfg *aquag2.Config, raw, from, to string) (string, error) {
	if cfg == nil {
		return "", fmt.Errorf("%w: %s", errNoConfigToRename, from)
	}
	owner, name, err := splitRepo(to)
	if err != nil {
		return "", err
	}
	cfg.RepoOwner, cfg.RepoName = owner, name
	lines := strings.Split(strings.TrimSuffix(raw, "\n"), "\n")
	if cfg.Name != "" {
		cfg.Name = to
		lines = setTopLevel(lines, "name", to)
	}
	lines = setTopLevel(lines, "repo_owner", owner)
	lines = setTopLevel(lines, "repo_name", name)
	if !hasAlias(cfg, from) {
		cfg.Aliases = append(cfg.Aliases, &aquaregistry.Alias{Name: from})
		lines = addAlias(lines, from)
	}
	return strings.Join(lines, "\n") + "\n", nil
}

// setTopLevel makes the top-level key say value, adding it after the package's name when the
// file doesn't have it.
func setTopLevel(lines []string, key, value string) []string {
	line := key + ": " + scalar(value)
	if i := topLevelIndex(lines, key); i >= 0 {
		lines[i] = line
		return lines
	}
	return slices.Insert(lines, topLevelIndex(lines, "name")+1, line)
}

// addAlias adds the name to the end of the top-level aliases, written the way the entries it
// already has are, and adds the list after the package's name when the file has none.
func addAlias(lines []string, name string) []string {
	i := topLevelIndex(lines, "aliases")
	if i < 0 || strings.TrimSpace(strings.TrimPrefix(lines[i], "aliases:")) != "" {
		// None, or one written inline, such as aliases: [], which becomes a block.
		if i >= 0 {
			lines = slices.Delete(lines, i, i+1)
		}
		at := topLevelIndex(lines, "name") + 1
		return slices.Insert(lines, at, "aliases:", "  - name: "+scalar(name))
	}
	indent := "  "
	last := i
	for j := i + 1; j < len(lines) && inBlock(lines[j]); j++ {
		if strings.TrimSpace(lines[j]) == "" {
			continue
		}
		if last == i {
			indent = lines[j][:len(lines[j])-len(strings.TrimLeft(lines[j], " "))]
		}
		last = j
	}
	return slices.Insert(lines, last+1, indent+"- name: "+scalar(name))
}

// inBlock reports whether a line can be part of the block a top-level key opens: one that is
// indented, an entry of a list written without indentation, a comment, or a blank line.
func inBlock(line string) bool {
	return line == "" || strings.HasPrefix(line, " ") || strings.HasPrefix(line, "-") || strings.HasPrefix(line, "#")
}

// topLevelIndex is the line the top-level key is on, or -1.
func topLevelIndex(lines []string, key string) int {
	for i, line := range lines {
		if line == key+":" || strings.HasPrefix(line, key+": ") {
			return i
		}
	}
	return -1
}

// scalar writes a value as YAML: as it is when it needs no quoting, which a package name
// doesn't, and quoted otherwise.
func scalar(value string) string {
	b, err := yaml.Marshal(value)
	if err != nil {
		return strconv.Quote(value)
	}
	return strings.TrimSuffix(string(b), "\n")
}

// splitRepo reads the owner and the repository out of a package name.
//
// A package name is usually the repository it comes from, and sometimes a command inside
// one: kubernetes/kubernetes/kubectl is the kubectl of kubernetes/kubernetes. The first
// two parts are the repository either way.
func splitRepo(pkgName string) (string, string, error) {
	parts := strings.SplitN(pkgName, "/", 3) //nolint:mnd
	if len(parts) < 2 || parts[0] == "" || parts[1] == "" {
		return "", "", fmt.Errorf("%w: %s", errNotARepoName, pkgName)
	}
	return parts[0], parts[1], nil
}

// hasAlias reports whether the definition already names it.
func hasAlias(cfg *aquag2.Config, name string) bool {
	for _, alias := range cfg.Aliases {
		if alias != nil && alias.Name == name {
			return true
		}
	}
	return false
}

// ErrNoBranchToRename says the rename failed because the registry doesn't hold the
// package.
//
// Which is not a failure of the rename so much as a rename with nothing to do: what the
// caller has to move is the package's place in its own records, and the registry only ever
// sees the new name.
func ErrNoBranchToRename(err error) bool {
	return errors.Is(err, errNoBranchToRename)
}

var (
	// errNoBranchToRename is what a rename of a package the registry doesn't hold gets.
	// There is nothing to carry over, and generating it under the new name is what the
	// ordinary run does.
	errNoBranchToRename = errors.New("the registry holds no such package to rename")
	// errNoConfigToRename is what a package with no definition gets. Its versions were
	// never generated, so the new name has nothing to inherit either.
	errNoConfigToRename = errors.New("the package has no definition")
	// errNotARepoName says a package name doesn't name a repository, which is what the
	// renamed definition has to record.
	errNotARepoName = errors.New("the package name doesn't name a repository")
)
